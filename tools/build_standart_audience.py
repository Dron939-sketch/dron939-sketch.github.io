def sub1(pattern, repl, s, flags=re.S):
    out, n = re.subn(pattern, lambda m: repl, s, count=1, flags=flags)
    assert n == 1, "не найдено: " + pattern[:60]
    return out


def main():
    src = io.open(SRC, encoding="utf-8").read()
    # Сцены основной страницы — по заголовку.
    block = re.search(r'<section id="cherez-mesyac">.*?</section>', src, re.S).group(0)
    scenes = {h3: full for full, h3 in
              re.findall(r'(  <div class="ex"><h3>([^<]+)</h3>.*?</div>)\n', block, re.S)}
    for key, v in VARIANTS.items():
        s = src
        s = sub1(r"<title>.*?</title>", "<title>%s</title>" % v["title"], s)
        s = sub1(r'<meta name="description" content="[^"]*">', '<meta name="description" content="%s">' % v["desc"], s)
        s = sub1(r'<span class="badge">[^<]*</span>', '<span class="badge">%s</span>' % v["badge"], s)
        s = sub1(r"<h1>.*?</h1>", "<h1>%s</h1>" % v["h1"], s)
        lead = "".join("   <p>%s</p>\n" % p for p in v["lead"]) + v.get("after_lead", "")
        s, n = re.subn(r'(<h1>.*?</h1>\n)   <p>.*?</p>\n   <p>.*?</p>\n',
                       lambda m: m.group(1) + lead, s, count=1, flags=re.S)
        assert n == 1, "врез первого экрана не найден"
        cards = "\n".join(scenes[x] if x in scenes else x for x in v["scenes"])
        new_block = re.sub(r'(  <div class="ex"><h3>.*</div>)\n(  <p><b>И вторая сторона)',
                           lambda m: cards + "\n" + m.group(2), block, count=1, flags=re.S)
        assert new_block != block
        s = s.replace(block, new_block, 1)
        s = s.replace("</body>", "<script>try{ym(108138656,'params',{standart_lp:'%s'})}catch(e){}</script>\n</body>" % key, 1)
        out = os.path.join(ROOT, "razgovornyj-gipnoz", "standart", key, "index.html")
        os.makedirs(os.path.dirname(out), exist_ok=True)
        io.open(out, "w", encoding="utf-8").write(s)
        print("записано:", os.path.relpath(out, ROOT))


if __name__ == "__main__":
    main()
