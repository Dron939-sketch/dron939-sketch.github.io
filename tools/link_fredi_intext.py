def insert(text: str, sentence: str) -> str | None:
    """Ставит абзац перед блоком вопросов. Возвращает None, если некуда."""
    m = FAQ_RE.search(text)
    if not m or MARK in text:
        return None
    para = (f'\n<p {MARK}>{sentence}</p>\n\n')
    return text[: m.start()] + para + text[m.start():]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    done = skipped = 0
    for slug, sentence in SENTENCES.items():
        path = BLOG / f"{slug}.html"
        if not path.exists():
            print(f"  нет файла: {slug}")
            skipped += 1
            continue
        text = path.read_text(encoding="utf-8")
        out = insert(text, sentence)
        if out is None:
            print(f"  пропуск (уже стоит или нет блока вопросов): {slug}")
            skipped += 1
            continue
        done += 1
        if not args.dry_run:
            path.write_text(out, encoding="utf-8")

    print(f"\nвставлено: {done}, пропущено: {skipped}")
    if args.dry_run:
        print("--dry-run: файлы не тронуты")

    # Разнообразие анкоров — то, ради чего всё затевалось.
    anchors = [re.search(r'>([^<]+)</a>', s).group(1) for s in SENTENCES.values()]
    print(f"анкоров: {len(anchors)}, различных: {len(set(anchors))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
