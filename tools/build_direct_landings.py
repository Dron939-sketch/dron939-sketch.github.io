def esc(s):
    return s.replace("&", "&amp;").replace('"', "&quot;").replace("<", "&lt;").replace(">", "&gt;")


def style():
    t = io.open(TEMPLATE, encoding="utf-8").read()
    return re.search(r"<style>(.*?)</style>", t, re.S).group(1).rstrip() + "\n" + EXTRA_CSS.strip()


