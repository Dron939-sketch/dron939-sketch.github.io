def clean(s):
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", s)).strip()


def build(cfg):
    b = BOOKS[cfg["book"]]
    paras = "\n".join('<p style="margin:0 0 10px">%s</p>' % x.format(title=b["title"]) for x in cfg["p"])
    items = "\n".join('<li style="margin:4px 0">%s</li>' % x for x in cfg["li"])
    return BOX_TPL.format(open=MARK_OPEN, close=MARK_CLOSE, head=cfg["head"], paras=paras,
                          items=items, **dict({"paid": PAID, "label": "Решение целиком — в книге"}, **b))


def insert(html, cfg, block):
    """Перед разделом, который идёт следом за разделом cfg['after']."""
    hs = [m for m in re.finditer(r"<h2[^>]*>(.*?)</h2>", html, re.S) if cfg["after"] in clean(m.group(1))]
    if not hs:
        return None
    nxt = html.find("<h2", hs[-1].end())
    if nxt < 0:
        return None
    pos = html.rfind("\n", 0, nxt) + 1
    # Комментарий-подпись или «mid-offer» прямо перед заголовком принадлежат
    # следующему разделу — блок встаёт выше них.
    while True:
        prev = html.rfind("\n", 0, pos - 1) + 1
        line = html[prev:pos].strip()
        if pos > 0 and (line == "" or line.startswith("<!--")):
            pos = prev
        else:
            break
    return html[:pos] + block + html[pos:]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--strip", action="store_true")
    args = ap.parse_args()
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from link_tovary import strip as strip_tovar

    changed = 0
    for slug, cfg in ARTICLES.items():
        path = os.path.join(ROOT, "blog", slug + ".html")
        src = open(path, encoding="utf-8").read()
        html = BLOCK_RE.sub("", src)
        if not args.strip:
            # Общая коробка той же книги в хвосте — вторая дверь, снимаем.
            html = strip_tovar(html)
            new = insert(html, cfg, build(cfg))
            if new is None:
                sys.exit("! %s: не найден раздел «%s»" % (slug, cfg["after"]))
            html = new
        state = "без изменений" if html == src else "обновлена"
        print("%-66s %s" % (slug, state))
        if html != src:
            changed += 1
            if not args.dry_run:
                open(path, "w", encoding="utf-8").write(html)
    print(("изменилось бы" if args.dry_run else "изменено"), "статей:", changed)


if __name__ == "__main__":
    main()
