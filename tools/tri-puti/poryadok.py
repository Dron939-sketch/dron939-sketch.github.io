# Шесть операций, у каждой — что должно быть готово до неё и сколько она
# длится. Один вход, один выход. Курсант строит порядок, называет срок,
# критическую цепь и пару параллельных. Вводная удлиняет операцию вне
# критической цепи так, что узкое место переезжает, — пятый шаг Голдратта.
def reach(edges, n=6):
    r = [[False] * n for _ in range(n)]
    for a, b in edges:
        r[a][b] = True
    for k in range(n):
        for i in range(n):
            for j in range(n):
                if r[i][k] and r[k][j]:
                    r[i][j] = True
    return r


def longest(edges, dur, n=6):
    """(финиш каждой операции, длина хвоста от операции до конца)"""
    order = sorted(range(n), key=lambda x: x)
    fin = [0] * n
    for v in order:
        fin[v] = max([fin[a] for a, b in edges if b == v] or [0]) + dur[v]
    tail = [0] * n
    for v in reversed(order):
        tail[v] = max([tail[b] for a, b in edges if a == v] or [0]) + dur[v]
    return fin, tail


def chain(edges, dur, n=6):
    fin, tail = longest(edges, dur, n)
    total = max(fin)
    ch, v = [], max(range(n), key=lambda x: tail[x] if fin[x] == dur[x] else -1)
    while True:
        ch.append(v)
        nxt = [b for a, b in edges if a == v]
        if not nxt:
            break
        v = max(nxt, key=lambda x: tail[x])
    return total, ch


def gen_dag(k):
    while True:
        n = 6
        edges = set()
        for i in range(n):
            for j in range(i + 1, n):
                if random.random() < 0.32:
                    edges.add((i, j))
        for j in range(1, n):
            if not any(b == j for a, b in edges):
                edges.add((random.randrange(j), j))
        for i in range(n - 1):
            if not any(a == i for a, b in edges):
                edges.add((i, random.randrange(i + 1, n)))
        if sum(1 for j in range(n) if not any(b == j for a, b in edges)) != 1:
            continue
        if sum(1 for i in range(n) if not any(a == i for a, b in edges)) != 1:
            continue
        r = reach(edges, n)
        red = {(a, b) for a, b in edges if not any(r[a][c] and r[c][b] for c in range(n))}
        dur = [random.choice(range(5, 45, 5)) for _ in range(n)]
        total, ch = chain(red, dur, n)
        off = [v for v in range(n) if v not in ch]
        par = [(i, j) for i in range(n) for j in range(i + 1, n) if not r[i][j] and not r[j][i]]
        if not off or not par:
            continue
        # вводная: операция вне цепи удлиняется — узкое место переезжает
        fin, tail = longest(red, dur, n)
        u = max(off, key=lambda v: fin[v] + tail[v] - dur[v])
        delta = total - (fin[u] + tail[u] - dur[u]) + random.choice([10, 15, 20])
        dur2 = list(dur)
        dur2[u] += delta
        total2, ch2 = chain(red, dur2, n)
        if ch2 == ch or u not in ch2:
            continue
        return dict(k=k, edges=sorted(red), dur=dur, total=total, ch=ch, par=par,
                    u=u, delta=delta, total2=total2, ch2=ch2)


