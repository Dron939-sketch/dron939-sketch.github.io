def key_block(sec, i, t, head=None):
    head = head or e(t.get("q") or t.get("sit") or "")
    return (f'<div class="task key"><span class="tn">{sec}-{i:02d}</span> {head} '
            f'<b>Правило:</b> {e(t["rule"])}. <b>Тип:</b> {e(t["typ"])}. <b>Продолжение:</b> {e(t["cont"])}; <b>порог:</b> {e(t["thr"])}. '
            f'<b>Поворот:</b> {e(t["turn"])}. <b>Коридор:</b> {e(t["corr"])}.'
            f'<p><b>Вводная: {e(t["vv"])}</b> → {e(t["after"])}.</p></div>')


