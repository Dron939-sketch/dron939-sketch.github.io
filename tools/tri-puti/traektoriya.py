def chart(t):
    W, Hh = 300, 110
    ml, mr, mt, mb = 28, 8, 8, 18
    ymax = t["ymax"]
    n = 10
    def X(i):
        return ml + (W - ml - mr) * (i - 1) / (n - 1)
    def Y(v):
        return mt + (Hh - mt - mb) * (1 - v / ymax)
    out = [f'<svg class="chart" viewBox="0 0 {W} {Hh}" width="{W}" height="{Hh}">',
           f'<rect x="0" y="0" width="{W}" height="{Hh}" fill="#fff"/>',
           f'<line x1="{ml}" y1="{Y(0)}" x2="{W-mr}" y2="{Y(0)}" stroke="#333" stroke-width=".8"/>',
           f'<line x1="{ml}" y1="{mt}" x2="{ml}" y2="{Y(0)}" stroke="#333" stroke-width=".8"/>']
    for i in range(1, n + 1):
        out.append(f'<line x1="{X(i)}" y1="{Y(0)}" x2="{X(i)}" y2="{Y(0)+3}" stroke="#333" stroke-width=".6"/>')
        out.append(f'<text x="{X(i)}" y="{Y(0)+11}" font-size="6.5" text-anchor="middle" fill="#333">{i}</text>')
    out.append(f'<text x="{ml-3}" y="{Y(ymax)+3}" font-size="6.5" text-anchor="end" fill="#333">{ymax:g}</text>')
    out.append(f'<text x="{ml-3}" y="{Y(0)+2}" font-size="6.5" text-anchor="end" fill="#333">0</text>')
    if t.get("thr_v") is not None and t["thr_v"] > 0:
        out.append(f'<line x1="{ml}" y1="{Y(t["thr_v"])}" x2="{W-mr}" y2="{Y(t["thr_v"])}" stroke="#7A1F1A" stroke-width=".7" stroke-dasharray="3 2"/>')
        out.append(f'<text x="{W-mr}" y="{Y(t["thr_v"])-2}" font-size="6.5" text-anchor="end" fill="#7A1F1A">{e(t["thr_label"])}</text>')
    def series(vals, dash=""):
        pts = " ".join(f'{X(i+1):.1f},{Y(v):.1f}' for i, v in enumerate(vals))
        out.append(f'<polyline points="{pts}" fill="none" stroke="#1F3A8A" stroke-width="1.1" {dash}/>')
        for i, v in enumerate(vals):
            out.append(f'<circle cx="{X(i+1):.1f}" cy="{Y(v):.1f}" r="2.2" fill="#1F3A8A"/>')
    series(t["vals"])
    if t.get("vals2"):
        series(t["vals2"], 'stroke-dasharray="4 2"')
    out.append(f'<text x="{X(len(t["vals"]))+4}" y="{mt+8}" font-size="6.5" fill="#666">дальше — курсант</text>')
    out.append('</svg>')
    return "".join(out)


