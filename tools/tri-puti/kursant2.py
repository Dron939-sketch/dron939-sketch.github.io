def task_block(num, lvl, sit, dano, nado, fact=True):
    return (f'<div class="task"><span class="tn">Задание {num}</span> <span class="lvl">{lvl}</span>'
            + (f'<p class="sit">{e(sit)}</p>' if sit else "")
            + f'<p><b>Дано:</b> {dano}.</p><p><b>Надо:</b> {nado}.</p>' + (FACT if fact else "") + LINES + '</div>')


def key_block(num, head, samples, closed):
    return f'<div class="task key"><span class="tn">{num}</span> {head}<p><b>Образцы:</b> {samples}. <b>Вводная: {closed}.</b></p></div>'


