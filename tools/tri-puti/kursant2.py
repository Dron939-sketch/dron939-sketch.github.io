BADGE = '<span class="badge">ОБРАЗЕЦ ВЫПОЛНЕНИЯ</span>'
SNOTE = ('Разбирается вслух вместе с курсантом до начала работы. Баллы не ставятся, норматив не включается. '
         'Со следующего задания курсант заполняет такие же строки сам.')


def F(v, dead=False):
    return f'<span class="fill{" dead" if dead else ""}">{e(v)}</span>'


def sample_block(num, s, dano, nado, sit=None, fact=True):
    h = f'<div class="task sample"><span class="tn">Задание {num}</span> {BADGE}'
    if sit:
        h += f'<p class="sit">{e(sit)}</p>'
    h += f'<p><b>Дано:</b> {dano}.</p><p><b>Надо:</b> {nado}.</p>'
    h += f'<p class="vv">Вводная инструктора: {e(s["vv"])}.</p>'
    if fact:
        h += f'<p class="ln">Фактически: {F(s["fact"])}</p>'
    tick = 0 if s["dead"] != 0 else 1          # галочка — на том, который пойдёт в дело
    marks = []
    for i, r in enumerate(s["routes"]):
        marks.append(f'Маршрут {i + 1} {F(r, i == s["dead"])} {"☑" if i == tick else "☐"}')
    h += '<p class="ln">' + ' &nbsp; '.join(marks) + ' &nbsp; баллы —</p>'
    h += f'<p class="ln">После вводной: {F(s["after"])}</p>'
    h += f'<p class="snote">{s["teach"]} {SNOTE}</p></div>'
    return h


