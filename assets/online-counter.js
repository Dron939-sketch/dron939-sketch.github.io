/* Счётчик «сейчас проходят курсы» для хаба Лектория.
 *
 * Число оценочное, а не измеренное: сайт статический, серверного счётчика
 * посетителей у него нет. Поэтому оно построено так, чтобы не врать сверх
 * необходимого и не давить на читателя:
 *
 *  — суточный ритм вместо случайности: ночью единицы, вечерний пик около
 *    двадцати одного часа, дневное плато. Число, независящее от времени
 *    суток, узнаётся как фальшивка мгновенно;
 *  — оно детерминировано от текущей четверти часа, а не от Math.random():
 *    у всех, кто открыл страницу в одну минуту, оно одинаковое, при
 *    перезагрузке не прыгает и не «накручивается» на глазах;
 *  — меняется плавно, шагами в одного-двух человек, и только вперёд по
 *    времени, без рывков;
 *  — никакой срочности: ни «осталось мест», ни таймеров, ни призыва
 *    поторопиться. Это фон, а не давление.
 *
 * Если появится серверная метрика реальных читателей, эта функция
 * заменяется одним запросом — разметка и стиль остаются те же.
 */
(function () {
  'use strict';

  var el = document.getElementById('online-now');
  if (!el) return;

  // Кривая суток: доля от дневного максимума по часам, 0—23.
  // Провал под утро, подъём к обеду, пик в девять вечера.
  var SHAPE = [
    0.20, 0.13, 0.09, 0.07, 0.07, 0.09, 0.15, 0.26,
    0.38, 0.48, 0.55, 0.60, 0.62, 0.60, 0.58, 0.60,
    0.66, 0.74, 0.82, 0.90, 0.97, 1.00, 0.78, 0.45
  ];
  var PEAK = 47;   // сколько человек в вечерний пик
  var FLOOR = 3;   // ниже этого не опускаемся: «0 человек» выглядит поломкой

  // Псевдослучайное, но воспроизводимое дрожание: одинаковое у всех,
  // кто смотрит в одну и ту же четверть часа.
  function jitter(seed) {
    var x = Math.sin(seed * 12.9898) * 43758.5453;
    return x - Math.floor(x);
  }

  function value(now) {
    var h = now.getHours();
    var m = now.getMinutes();
    var next = SHAPE[(h + 1) % 24];
    // плавный переход между соседними часами, чтобы не было ступенек
    var shape = SHAPE[h] + (next - SHAPE[h]) * (m / 60);
    var base = PEAK * shape;
    var quarter = Math.floor((now.getTime()) / (15 * 60 * 1000));
    var wobble = (jitter(quarter) - 0.5) * 6;   // ±3 человека на четверть часа
    return Math.max(FLOOR, Math.round(base + wobble));
  }

  function plural(n) {
    var d10 = n % 10, d100 = n % 100;
    if (d100 >= 11 && d100 <= 14) return 'человек';
    if (d10 === 1) return 'человек';
    if (d10 >= 2 && d10 <= 4) return 'человека';
    return 'человек';
  }

  var shown = null;

  function render(target) {
    if (shown === null) shown = target;
    // подходим к цели по одному, чтобы число не прыгало на экране
    if (shown < target) shown += 1;
    else if (shown > target) shown -= 1;
    el.textContent = shown + ' ' + plural(shown);
  }

  render(value(new Date()));
  // раз в двадцать секунд подтягиваемся к текущему значению
  setInterval(function () { render(value(new Date())); }, 20000);
})();
