/* Лекции Лектория: текст лекции не выделяется и не копируется.
 *
 * На индексацию не влияет. Разметка страницы не меняется, текст остаётся в
 * HTML как был: краулер и языковая модель читают исходник, а не выделяют
 * текст мышью. Ничего не прячется и не подменяется — то есть это не клоакинг
 * и не повод для санкций.
 *
 * Защита не абсолютная и не может быть таковой: исходный код страницы
 * открыт всегда. Это заслон от бездумного «выделил — скопировал», не больше.
 *
 * Скринридеру не мешает: user-select не трогает дерево доступности.
 */
(function () {
  var art = document.querySelector(".article-content");
  if (!art) return;

  function stop(e) {
    e.preventDefault();
  }

  ["copy", "cut", "dragstart", "contextmenu"].forEach(function (type) {
    art.addEventListener(type, stop);
  });
})();
